/**
 * Document files on Android: encrypted with each file's own key and kept in
 * the app's private folder, so a file stays readable even if the original in
 * Downloads or WhatsApp is deleted. Opened into the cache only to show or
 * share it.
 */
import { Directory, File, Paths } from 'expo-file-system';
import * as Sharing from 'expo-sharing';

import type { FileRef } from '@/domain/types';
import { extensionOf } from '@/domain/validation';
import { decryptFile, encryptFile, fromB64, initCrypto } from '@/lib/crypto';
import { fileContext } from '@/sync/contexts';

export interface PickedFile {
  uri: string;
  name: string;
  mime?: string;
  size?: number;
  /** Web only: the picked File object. */
  blob?: Blob;
}

type Remote = (familyId: string, fileId: string) => Promise<Uint8Array | null>;
let remote: Remote | null = null;

export function setFileRemote(fetcher: Remote | null): void {
  remote = fetcher;
}

function folder(name = 'files', base = Paths.document): Directory {
  const dir = new Directory(base, name);
  if (!dir.exists) dir.create({ intermediates: true, idempotent: true });
  return dir;
}

const stored = (id: string) => new File(folder(), `${id}.bin`);
const locked = (ref: Pick<FileRef, 'key' | 'familyId'>): ref is { key: string; familyId: string } => !!ref.key && !!ref.familyId;

export const cipherStore = {
  read: async (id: string) => (stored(id).exists ? stored(id).bytes() : null),
  write: async (id: string, bytes: Uint8Array) => {
    const f = stored(id);
    f.create({ overwrite: true });
    await f.write(bytes);
  },
  has: async (id: string) => stored(id).exists,
  forget: async (id: string) => {
    if (stored(id).exists) stored(id).delete();
  },
};

export async function saveFile(ref: FileRef, picked: PickedFile): Promise<void> {
  const plain = await new File(picked.uri).bytes();
  const bytes = locked(ref) ? (await initCrypto(), encryptFile(plain, fromB64(ref.key), fileContext(ref.familyId, ref.id))) : plain;
  await cipherStore.write(ref.id, bytes);
}

export async function fileBytes(ref: FileRef): Promise<Uint8Array | null> {
  let bytes: Uint8Array | null = await cipherStore.read(ref.id);
  if (!bytes && locked(ref) && remote) {
    bytes = await remote(ref.familyId, ref.id);
    if (bytes) await cipherStore.write(ref.id, bytes);
  }
  if (!bytes) return null;
  if (!locked(ref)) return bytes;
  await initCrypto();
  return decryptFile(bytes, fromB64(ref.key), fileContext(ref.familyId, ref.id));
}

/** An opened copy in the cache, for showing the file. */
export async function fileUrl(ref: FileRef): Promise<string | null> {
  const bytes = await fileBytes(ref);
  if (!bytes) return null;
  const ext = extensionOf(ref.name);
  const out = new File(folder('open', Paths.cache), ext ? `${ref.id}.${ext}` : ref.id);
  out.create({ overwrite: true });
  await out.write(bytes);
  return out.uri;
}

export async function removeFile(ref: Pick<FileRef, 'id'>): Promise<void> {
  await cipherStore.forget(ref.id);
}

/** Writes generated bytes (a PDF, a resized photo) to a temporary file and opens the share sheet. */
export async function shareBytes(bytes: Uint8Array, name: string, mime: string): Promise<boolean> {
  const out = new File(Paths.cache, name);
  out.create({ overwrite: true });
  await out.write(bytes);
  if (!(await Sharing.isAvailableAsync())) return false;
  await Sharing.shareAsync(out.uri, { mimeType: mime, dialogTitle: name });
  return true;
}

/** Shares a file that already exists on the phone (a masked or resized image). */
export async function shareUri(uri: string, name: string, mime: string): Promise<boolean> {
  const source = new File(uri);
  const out = new File(Paths.cache, name);
  if (out.exists) out.delete();
  await source.copy(out);
  if (!(await Sharing.isAvailableAsync())) return false;
  await Sharing.shareAsync(out.uri, { mimeType: mime, dialogTitle: name });
  return true;
}

/** Shares an image made on the phone (masked copy, resized photo). */
export async function shareResult(result: { uri: string; blob?: Blob }, name: string, mime: string): Promise<boolean> {
  return shareUri(result.uri, name, mime);
}

/** Opens the phone's share sheet (WhatsApp, Gmail, Drive...). */
export async function shareFile(ref: FileRef): Promise<boolean> {
  const bytes = await fileBytes(ref);
  if (!bytes) return false;
  return shareBytes(bytes, ref.name, ref.mime);
}
