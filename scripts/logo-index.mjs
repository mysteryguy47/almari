// Writes src/components/logo-assets.ts from the files in assets/logos.
// Run after adding or replacing a logo: node scripts/logo-index.mjs
//
// Bank logos are named by the first four letters of the bank's IFSC, in
// lower case (sbin.webp, hdfc.webp). Source: github.com/praveenpuglia/indian-banks.
// Document logos are named for the office that issues the paper (aadhaar,
// income-tax, eci), from Wikimedia Commons and Wikipedia.
// Paper and category pictures (papers/driving-licence.webp, categories/home.webp)
// are drawn from Microsoft's Fluent Emoji (MIT licence), a picture and, where
// papers are alike, a smaller one in the corner (an ID card with a car on it).
// Each is trimmed to its edges, at most 160 px on the long side, WebP.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');

/** Width over height, read from the WebP header (lossy, lossless or extended). */
function aspect(file) {
  const b = readFileSync(file);
  const chunk = b.toString('ascii', 12, 16);
  let w;
  let h;
  if (chunk === 'VP8X') {
    w = 1 + b.readUIntLE(24, 3);
    h = 1 + b.readUIntLE(27, 3);
  } else if (chunk === 'VP8L') {
    const bits = b.readUInt32LE(21);
    w = 1 + (bits & 0x3fff);
    h = 1 + ((bits >> 14) & 0x3fff);
  } else {
    w = b.readUInt16LE(26) & 0x3fff;
    h = b.readUInt16LE(28) & 0x3fff;
  }
  return Math.round((w / h) * 100) / 100;
}

const key = (name) => (/^[a-z_$][a-z0-9_$]*$/i.test(name) ? name : `'${name}'`);
const list = (dir) => readdirSync(join(root, 'assets/logos', dir)).filter((f) => f.endsWith('.webp')).sort();
const entries = (dir) =>
  list(dir)
    .map((f) => `  ${key(f.replace(/\.webp$/, ''))}: { source: require('../../assets/logos/${dir}/${f}'), aspect: ${aspect(join(root, 'assets/logos', dir, f))} },`)
    .join('\n');

writeFileSync(
  join(root, 'src/components/logo-assets.ts'),
  `// Generated by scripts/logo-index.mjs from assets/logos. Do not edit by hand.

export interface LogoAsset {
  /** The bundled file, as require() gives it. */
  source: number;
  /** Width over height. */
  aspect: number;
}

/** Bank logos by the first four letters of the IFSC, in lower case. */
export const BANK_LOGOS: Record<string, LogoAsset> = {
${entries('banks')}
};

/** Logos of the offices that issue papers (UIDAI, Income Tax, ECI) and of card issuers. */
export const DOC_LOGOS: Record<string, LogoAsset> = {
${entries('docs')}
};

/** A picture for each paper without an issuer's logo, by template id. */
export const PAPER_ART: Record<string, LogoAsset> = {
${entries('papers')}
};

/** A picture for each category, by category id. */
export const CATEGORY_ART: Record<string, LogoAsset> = {
${entries('categories')}
};
`,
);
console.log(
  `${list('banks').length} bank logos, ${list('docs').length} document logos, ${list('papers').length} paper pictures, ${list('categories').length} category pictures`,
);
